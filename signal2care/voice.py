def plain(metric: str) -> tuple[str, str]:
    return PLAIN.get(metric, (metric.replace("_", " "), ""))


def cap(s: str) -> str:
    return s[:1].upper() + s[1:]


def num(x: float) -> str:
    x = float(x)
    return f"{x:.1f}".rstrip("0").rstrip(".") if abs(x) < 1000 else f"{x:.0f}"


def hours_phrase(h: int) -> str:
    return "about an hour" if h <= 1 else f"about {h} hours"


def name_greeting(name: str | None) -> str:
    return f"Hi {name}. " if name else ""


# ----------------------------------------------------------------------- alerts
def alert_text(metric: str, value: float, baseline: float, hours: int, kind: str, question_key: str, *, name: str | None = None,
               first_alert: bool = False) -> tuple[str, list[str]]:
    """The alert message and the phrases to make bold. Plain words, one question."""
    label, unit = plain(metric)
    higher = value > baseline
    if kind == "gap":
        head = "Your band has not sent data for a while."
        body = f"It has been {hours_phrase(hours)}."
    elif metric == "sleep_hours":
        head = "You slept less than usual." if not higher else "You slept more than usual."
        body = f"You slept {num(value)} hours. Your usual is {num(baseline)} hours."
    elif metric in ("skin_temp", "spo2"):
        head = f"Your {label} is {'higher' if higher else 'lower'} than usual."
        diff = abs(value - baseline)
        now_txt = f"{num(value)} \u00b0C" if metric == "skin_temp" else f"{num(value)}%"
        unit_diff = "\u00b0C" if metric == "skin_temp" else "points"
        where = "above" if higher else "below"
        body = f"It is {now_txt}, which is {num(diff)} {unit_diff} {where} your usual {num(baseline)}."
        if kind == "hourly" and hours > 1:
            body += f" It has stayed that way for {hours_phrase(hours)}."
    else:
        head = f"Your {label} is {'higher' if higher else 'lower'} than usual."
        body = f"It is {num(value)} {unit}. Your usual is {num(baseline)}."
        if kind == "hourly" and hours > 1:
            body += f" It has stayed that way for {hours_phrase(hours)}."
    q = QUESTIONS[question_key][0]
    family = FAMILY.get(metric, "other")
    parts = [f"{name_greeting(name)}{cap(head)}".strip(), body, q]
    if family in SAFETY_FAMILIES and kind != "gap":
        parts.append(SAFETY_LINE)
    if first_alert:
        parts.append("Tip: tap \U0001F44D on this message if it looks fine, or \U0001F44E if it looks wrong.")
    text = "\n\n".join(parts)
    return text, [cap(head)]


def update_text(metric: str, before: str, after: str, why: str, lead: str = "") -> tuple[str, list[str]]:
    label, _ = plain(metric)
    head = f"Update on your {label} alert"
    lead_part = f"{lead}\n\n" if lead else ""
    text = f"{head}\n\n{lead_part}Before: {before}\n\nNow: {after}\n\nWhy: {why}\n\nThis describes your numbers. It does not prove a cause."
    return text, [head]


def closing_text(summary: str, name: str | None = None) -> tuple[str, list[str]]:
    head = "Saved to your record"
    text = (f"{head}\n\n{summary}\n\nWant to change anything? Say \"correct that\" and tell me what is right, or say \"forget that\" "
            "and I will remove it.")
    return text, [head]


